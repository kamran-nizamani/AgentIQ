import { describe, expect, it } from "vitest";
import { formatRemediationPlanMarkdown } from "./remediation-plan.js";

describe("formatRemediationPlanMarkdown", () => {
  it("exports a numbered checklist with a timestamp and safety boundary", () => {
    const markdown = formatRemediationPlanMarkdown(
      { title: "CI remediation plan · build", steps: [" Inspect the failed job. ", "Add a regression test."], proposal: "Fix the failing build step.", priority: { score: 92, label: "Critical" }, evidenceUrl: "https://github.com/example/repo/actions/runs/1", evidenceLabel: "Workflow run", approved: true, safetyChecks: ["Regression test defined"] },
      new Date("2026-10-12T06:00:00.000Z"),
    );
    expect(markdown).toContain("# CI remediation plan · build");
    expect(markdown).toContain("Generated by AgentIQ on 2026-10-12T06:00:00.000Z.");
    expect(markdown).toContain("## Priority");
    expect(markdown).toContain("92/100 · Critical");
    expect(markdown).toContain("Fix the failing build step.");
    expect(markdown).toContain("https://github.com/example/repo/actions/runs/1");
    expect(markdown).toContain("Approved for manual implementation");
    expect(markdown).toContain("- Regression test defined");
    expect(markdown).toContain("1. Inspect the failed job.");
    expect(markdown).toContain("2. Add a regression test.");
    expect(markdown).toContain("No repository files were changed");
  });

  it("handles an empty checklist without producing a broken document", () => {
    expect(formatRemediationPlanMarkdown({ title: "Empty plan", steps: [] })).toContain("No steps were provided.");
  });
});
